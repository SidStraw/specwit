import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

// Compile text assets into the executable so npm installs and a copied bundle
// have identical behavior without depending on this checkout or the cwd.
const resources = fileURLToPath(new URL('../resources/', import.meta.url))
function readDirectory(directory) {
  const entries = {}
  function walk(current, prefix = '') {
    for (const entry of readdirSync(current, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
      const ref = prefix + entry.name
      if (entry.isDirectory()) walk(join(current, entry.name), ref + '/')
      else entries[ref] = readFileSync(join(current, entry.name), 'utf8')
    }
  }
  walk(directory)
  return entries
}
const locales = Object.fromEntries(['en', 'zh-TW'].map(language => [language, readDirectory(join(resources, language))]))
if (JSON.stringify(Object.keys(locales.en)) !== JSON.stringify(Object.keys(locales['zh-TW'])))
  throw new Error('English and Traditional Chinese resources must have the same files.')
const common = readDirectory(join(resources, 'common'))
mkdirSync(new URL('../generated/', import.meta.url), { recursive: true })
writeFileSync(new URL('../generated/resources.ts', import.meta.url), `// Generated by scripts/resources.mjs; edit resources/ instead.\nexport const localizedResources: Record<string, Record<string, string>> = ${JSON.stringify(locales, null, 2)}\nexport const commonResources: Record<string, string> = ${JSON.stringify(common, null, 2)}\n`)
